"""Compiles a directory of GLSL shaders into a Clarus module of shader blobs.

    python clarus/shaders.py SRC OUT [NAME]

compiles every SRC/*.vert, *.frag and *.comp (a .glsl beside them is only
#included) and writes the module OUT/: shaders.h holds each blob as static
data, and shaders.clarus one function for each file, `smoke.vert` being
`fn smoke_vert() -> Ptr<const gfx.VertShader>`, which gfx.pipeline() takes.
A program imports it as `import shaders`.

With a NAME, the files are NAME.clarus and NAME.h, added to the module OUT/
of a library (gfx and ui use it for their own shaders): the functions are
private to it and their C names carry NAME, so they meet no program's.

The blobs are what Goose's `embed_shader` makes (vietnt/goose src/shaderc.c):
SPIR-V, MSL and HLSL together with their reflection, so one blob serves Vulkan,
Metal and Direct3D 12, and the same OUT builds on every machine. They come from
the `goose` on PATH, which compiles a small generated program that writes each
blob to a file, so a GLSL error or a broken SDL_GPU binding rule fails here,
with the shader's file and line, as it fails a Goose build.
"""

import subprocess
import sys
import tempfile
from pathlib import Path

STAGES = {".vert": "VertShader", ".frag": "FragShader", ".comp": "CompShader"}


def ident(p):
    return "".join(c if c.isalnum() else "_" for c in p.name)


def main():
    src, out = Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve()
    name = sys.argv[3] if len(sys.argv) > 3 else "shaders"
    # gfx's own shaders are in gfx, which cannot import itself.
    gfx = "" if out.name == "gfx" else "gfx."
    vis = "" if name == "shaders" else "private "
    sym = "gsc_shader" if name == "shaders" else f"gsc_{name}"
    files = sorted(p for p in src.iterdir() if p.suffix in STAGES)
    if not files:
        sys.exit(f"shaders: no .vert, .frag or .comp in {src}")
    out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        lines = ["import std;", "import os;", "fn main() {"]
        for p in files:
            lines.append(f'    guard write_file("{(tmp / ident(p)).as_posix()}", '
                         f'embed_shader("{p.as_posix()}")) else {{ abort("cannot write"); }}')
        lines.append("}")
        prog = tmp / "blobs.goose"
        prog.write_text("\n".join(lines) + "\n")
        subprocess.run(["goose", "run", str(prog)], check=True)
        blobs = {p: (tmp / ident(p)).read_bytes() for p in files}

    h = ["/* Generated by goose_gfx/clarus/shaders.py from " + src.name + "/. Do not edit. */",
         '#include "gsc_shader.h"', ""]
    c = ["// Generated by goose_gfx/clarus/shaders.py from " + src.name + "/. Do not edit.",
         "// The shader blobs, one function for each file (gfx.pipeline takes them).", "",
         *(["import gfx"] if gfx else []), f'include "{name}.h"', ""]
    for p, b in blobs.items():
        n, t = ident(p), STAGES[p.suffix]
        body = ",".join(str(x) for x in b)
        h += [f"static const uint8_t {sym}_blob_{n}[{len(b)}] = {{{body}}};",
              f"static const {t} {sym}_{n}_data = {{ {sym}_blob_{n}, {len(b)} }};",
              f"static inline const {t} *{sym}_{n}(void) {{ return &{sym}_{n}_data; }}", ""]
        c += [f"private extern fn {sym}_{n}() -> Ptr<const {gfx}{t}>",
              f"{vis}fn {n}() -> Ptr<const {gfx}{t}> {{ return {sym}_{n}() }}", ""]
    (out / f"{name}.h").write_text("\n".join(h))
    (out / f"{name}.clarus").write_text("\n".join(c))
    print(f"shaders: {len(files)} into {out}")


if __name__ == "__main__":
    main()
